export function detectStack(html: string, headers: Record<string, string>): TechStack {
  const h = Object.fromEntries(Object.entries(headers).map(([k, v]) => [k.toLowerCase(), v]));
  const found = new Map<string, Tech>();
  for (const r of RULES) {
    const byHtml = r.html?.test(html);
    const byHeader = r.header ? r.header[1].test(h[r.header[0]] ?? "") && !!h[r.header[0]] : false;
    if (!byHtml && !byHeader) continue;
    const version = r.version ? (html.match(r.version)?.[1] ?? h["x-powered-by"]?.match(r.version)?.[1]) : undefined;
    if (!found.has(r.name)) found.set(r.name, { name: r.name, group: r.group, ...(version ? { version } : {}) });
  }
  const wpPlugins = [...new Set([...html.matchAll(/\/wp-content\/plugins\/([a-z0-9-_]+)\//gi)].map((m) => m[1].toLowerCase()))].sort().slice(0, 40);
  const technologies = [...found.values()];
  return { technologies, wpPlugins, pitch: pitchFor(technologies), checkedAt: new Date().toISOString() };
}

/** Talking points from what the site uses and what it lacks. */
export function pitchFor(t: Tech[]) {
  const has = (name: string) => t.some((x) => x.name === name);
  const group = (g: TechGroup) => t.filter((x) => x.group === g);
  const out: string[] = [];
  const platform = group("Platform")[0]?.name;
  if (platform === "WordPress" && !group("SEO plugin").length) out.push("WordPress without an SEO plugin (Yoast, Rank Math…): titles, sitemaps and schema are probably not managed.");
  if (platform === "WordPress" && !group("Speed / cache").length) out.push("WordPress with no caching plugin found: pages are likely slower than they need to be.");
  if (platform === "WordPress" && group("Page builder").length) out.push(`Built with ${group("Page builder")[0].name}: heavy page builders often slow pages down — speed work is a strong offer.`);
  if (platform && ["Wix", "Squarespace", "GoDaddy Website Builder", "Weebly", "Duda"].includes(platform)) out.push(`${platform} site: some SEO controls are limited on this platform — local SEO, content and Google Business Profile work matter even more.`);
  if (!has("Google Analytics") && !has("Google Tag Manager")) out.push("No Google Analytics or Tag Manager found: they are not measuring visitors or enquiries — set it up as part of the first month.");
  if (!group("Chat").length && !group("Booking").length) out.push("No chat, WhatsApp button or online booking: visitors can only call or email — an easy conversion win.");
  if (has("Meta Pixel") || has("Google Ads tag") || has("TikTok Pixel")) out.push("They run paid ads (an ads pixel is installed): they already spend on marketing, so SEO that lowers that cost is an easy sell.");
  const php = t.find((x) => x.name === "PHP")?.version;
  if (php && Number(php.split(".")[0]) < 8) out.push(`The server shows PHP ${php}, which is out of date: a security and speed risk.`);
  return out;
}
